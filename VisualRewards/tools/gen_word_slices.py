#!/usr/bin/env python3
"""gen_word_slices.py -- the SOTN entrance's slices of every Word Font glyph (owner 11-16 07:59, "sotn style"). Tool only;
never ships. Do not hand-edit what it writes.

    python3 -I VisualRewards/tools/gen_word_slices.py

A word over a monster (rsqvr/words.zs) comes in as the banners' SOTN letters do: for its first 4 tics it is stretched wide
and slanted forward, then snaps upright. A world word is one VisualThinker quad per letter, and a quad can be scaled and
moved but not sheared, so the slant is made as the banners make theirs (banners.zs SlantTex: horizontal slices, the top ones
further ahead): each glyph is drawn in its smear tics as FOUR slices, each one moved sideways by the slant at its own
height. A quad cannot be cropped at draw time, so the slices are cut here, in TEXTURES: no new art, only definitions over the
existing glyphs, as gen_sotn_halves.py / gen_word_fonts.py cut the SOTN two-tone halves.

THE CUTS are on whole font rows (the pixels stay whole), and slices 1-2 are exactly the glyph's top half, 3-4 its bottom half
(the halves' split, rows // 2), so a word in the SOTN two-tone look keeps its two colours while it smears:
    R = cell height in font rows, T = R // 2 (the halves' split), cuts at 0, ceil(T / 2), T, T + ceil((R - T) / 2), R
words.zs SliceB() makes the same cuts from the glyph's height, to move each slice by the slant at its middle.

WHAT IT WRITES  pk3/TEXTURES.rsqvrsl, per glyph nnn of each font (prefix P: QWS Score Small, QWO SOTN, QWJ JFO, QV Score Big,
QWD Doom small), slice j 1..4:
  P<c>nnn  the slice's rows, cut from the full glyph (c = E G I K for slices 1..4)
  P<j>nnn  that slice in a full-size cell with the full glyph's own centre offset (so it lines up exactly with the glyph)
Sizes are read from the glyphs themselves: pk3/graphics/rsqvrwf/QW{S,O,J}Wnnn.png, pk3/graphics/rsqvrw/QVWnnn.png, and
TEXTURES.rsqvrwf's QWDWnnn definitions (Doom small is the IWAD's STCFN, by TEXTURES).
"""
import os, re
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PK3 = os.path.join(os.path.dirname(HERE), 'pk3')
OUT = os.path.join(PK3, 'TEXTURES.rsqvrsl')
CROP = 'EGIK'

# font: (prefix, texture px per font px) -- words.zs WF_NAME / WF_K
FONTS = [('QWS', 4), ('QWO', 4), ('QWJ', 1), ('QV', 4), ('QWD', 1)]


def cuts(h, k):
    r = h // k
    t = r // 2
    return [0, ((t + 1) // 2) * k, t * k, (t + (r - t + 1) // 2) * k, h]


def sizes(prefix):
    out = {}
    if prefix == 'QWD':
        for m in re.finditer(r'Graphic "QWDW(\d{3})", (\d+), (\d+)', open(os.path.join(PK3, 'TEXTURES.rsqvrwf')).read()):
            out[int(m.group(1))] = (int(m.group(2)), int(m.group(3)))
        return out
    d = os.path.join(PK3, 'graphics', 'rsqvrw' if prefix == 'QV' else 'rsqvrwf')
    for f in os.listdir(d):
        if f.startswith(prefix + 'W') and f.endswith('.png'):
            out[int(f[len(prefix) + 1:len(prefix) + 4])] = Image.open(os.path.join(d, f)).size
    return out


def main():
    L = ['// GENERATED by tools/gen_word_slices.py -- do not hand-edit.',
         '// The SOTN entrance\'s slant (rsqvr/words.zs): every Word Font glyph cut into four horizontal slices on whole font rows',
         '// (slices 1-2 its top half, 3-4 its bottom half); P<E,G,I,K>nnn the slices, P<1..4>nnn each in a full-size cell',
         '// with the glyph\'s own centre offset. No new art.', '']
    n = 0
    for prefix, k in FONTS:
        sz = sizes(prefix)
        for c in sorted(sz):
            w, h = sz[c]
            b = cuts(h, k)
            g = '%sW%03d' % (prefix, c)
            for j in range(4):
                y0, y1 = b[j], b[j + 1]
                cr = '%s%s%03d' % (prefix, CROP[j], c)
                L += ['Graphic "%s", %d, %d' % (cr, w, y1 - y0), '{', '\tPatch "%s", 0, %d' % (g, -y0), '}',
                      'Graphic "%s%d%03d", %d, %d' % (prefix, j + 1, c, w, h), '{', '\tOffset %d, %d' % (w // 2, h // 2),
                      '\tPatch "%s", 0, %d' % (cr, y0), '}']
                n += 2
            L.append('')
        print('%s: %d glyphs, cuts for a %d-px cell: %s' % (prefix, len(sz), h, cuts(h, k)))
    open(OUT, 'w').write('\n'.join(L))
    print('wrote %d definitions in %s' % (n, OUT))


if __name__ == '__main__':
    main()
