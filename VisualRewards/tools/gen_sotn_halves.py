#!/usr/bin/env python3
"""gen_sotn_halves.py -- the SOTN two-tone words' glyph halves (LegenDoom HUD, direction D, owner 11-11 15:30). Tool only;
never ships. Do not hand-edit what it writes.

    python3 -I VisualRewards/tools/gen_sotn_halves.py

The SOTN style A word (design/mockups/sotn_words/, the look the owner picked on 11-10) is two-toned: the top half of each
letter in one colour, the bottom half in another (design/mockups/legendoom_hud/src/make_mockups.py sotn()). A world word
is one VisualThinker quad per letter, and a quad cannot be cropped at draw time, so the crop is made in TEXTURES: no new
art, only definitions over the existing glyphs (pk3/graphics/rsqvrw/QVWnnn.png, RS Score's font made by gen_beams.py).

WHAT IT WRITES  pk3/TEXTURES.rsqvrsotn, four definitions per glyph nnn (33..96):
  QVHnnn  the glyph's top half (rows 0..H/2-1), H/2 tall          QVLnnn  its bottom half (rows H/2..H-1), H/2 tall
  QVTnnn  QVHnnn at the top of a full-size cell (the rest clear)  QVBnnn  QVLnnn at the bottom of a full-size cell
QVTnnn and QVBnnn are the full glyph's size with the full glyph's offset (its centre, as gen_beams.py grAbs it), so the two
halves drawn at the glyph's own place and scale line up exactly with it (rsqvr/words.zs, a word's "sotn" look).
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PK3 = os.path.join(os.path.dirname(HERE), 'pk3')
GFX = os.path.join(PK3, 'graphics', 'rsqvrw')
OUT = os.path.join(PK3, 'TEXTURES.rsqvrsotn')

L = ['// GENERATED by tools/gen_sotn_halves.py -- do not hand-edit.',
     '// The SOTN two-tone words: each RS Score glyph QVWnnn (gen_beams.py) cut into its top and bottom halves, no new art.',
     '// QVH/QVL: the halves; QVT/QVB: each half in a full-size cell with the glyph\'s own centre offset (rsqvr/words.zs).',
     '']
n = 0
for c in range(33, 97):
    p = os.path.join(GFX, 'QVW%03d.png' % c)
    if not os.path.exists(p):
        continue
    w, h = Image.open(p).size
    t = h // 2
    g = 'QVW%03d' % c
    L += ['Graphic "QVH%03d", %d, %d' % (c, w, t), '{', '\tPatch "%s", 0, 0' % g, '}',
          'Graphic "QVL%03d", %d, %d' % (c, w, h - t), '{', '\tPatch "%s", 0, %d' % (g, -t), '}',
          'Graphic "QVT%03d", %d, %d' % (c, w, h), '{', '\tOffset %d, %d' % (w // 2, h // 2), '\tPatch "QVH%03d", 0, 0' % c, '}',
          'Graphic "QVB%03d", %d, %d' % (c, w, h), '{', '\tOffset %d, %d' % (w // 2, h // 2), '\tPatch "QVL%03d", 0, %d' % (c, t), '}', '']
    n += 1
open(OUT, 'w').write('\n'.join(L))
print('wrote %s: %d glyphs' % (OUT, n))
