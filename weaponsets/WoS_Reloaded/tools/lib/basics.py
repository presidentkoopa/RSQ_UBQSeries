"""The weapon sets' basics (owner 2026-11-13): "the mods themselves will have basic pistol whip, jab hook uppercut, lift
doors, uppercut barrels, quick grenade (give WoS and GNRC our RS Grenade as a slot 0 item, but don't give them the fancy
alt fires, just our normal bouncy grenade with a regular doom explosion graphic and x2 barrel damage)". RSQ Melee keeps
the advanced suite: each basic stands down when the series mod that owns it is loaded.

    the grenade   RSQ Grenade's own code (Grenade/zscript/rsqgn: weapon, hand, thrown, upg, scatter), RSQGN_ -> RSQB_GN_,
                  slot 0, the frag only, Doom's explosion, barrels take the blast twice. Stands down for RSQ_Grenade.pk3
                  (its own stand-down for BD22 VR, pointed at RSQ Grenade).
    the doors     RSQ Distance Grab's door lift (DistanceGrab/zscript/rsqdg/door.zs), RSQDG_ -> RSQB_DG_. Stands down for
                  Distance Grab.
    the fists     BD22 VR's real punches (zscript/rsq/fists.zs, ported by build.py's zs_port with patches from here):
                  jab, hook and uppercut, an uppercut into a barrel kicks it up and away. Stand down for RSQ Melee.
    the whip      BD22 VR's pistol whip (zscript/rsvr/melee.zs, its PISTOL kind; build.py's melee patch).
Both weapon sets carry an identical copy of this file (they never load together)."""
import os, re, shutil
SERIES = '/home/claude/rsq_ubqseries'
GN = os.path.join(SERIES, 'Grenade')
DG = os.path.join(SERIES, 'DistanceGrab')

def _gn(t):
    t = t.replace('RSQGN_', 'RSQB_GN_')
    t = re.sub(r'\brsqgn_', 'rsqb_gn_', t)		# cvars, events, random names; sound names ("rsqgn/...") stay
    return t

def _must(t, a, b, n=1, what=''):
    c = t.count(a)
    if c != n: raise SystemExit('basics: %s: %r hits %d (want %d)' % (what, a[:70], c, n))
    return t.replace(a, b)

def grenade(tree):
    out = []
    files = ['weapon', 'hand', 'thrown', 'upg', 'scatter']
    for f in files:
        t = _gn(open(os.path.join(GN, 'zscript/rsqgn/%s.zs' % f), encoding='latin-1').read())
        t = '// GENERATED by tools/lib/basics.py from RSQ Grenade\'s zscript/rsqgn/%s.zs (the weapon sets\' basic grenade)\n' % f + t
        if f == 'weapon':
            t = _must(t, 'Weapon.SlotNumber 9;', 'Weapon.SlotNumber 0;\t// the weapon sets: slot 0 (owner 2026-11-13)', 1, f)
        if f == 'hand':
            # stands down for RSQ Grenade itself, the way RSQ Grenade stands down for BD22 VR's grenade
            t = _must(t, 'String n = "RSG_Handler";', 'String n = "RSQGN_Handler";\t// the weapon sets: RSQ_Grenade.pk3 is loaded, this basic grenade stands down', 1, f)
        if f == 'upg':
            # the series' barrels (Grapple 2.0's air spike) and the kinds' turned monsters are not in the basics
            t, n = re.subn(r'\t\tif \(request == "g2\.neon"\)\n\t\t\{.*?\n\t\t\}\n', '\t\tif (request == "g2.neon") return 0;\t// the weapon sets: no series barrels here\n', t, count=1, flags=re.S)
            if n != 1: raise SystemExit('basics: upg g2.neon')
            t = _must(t, 'let t = a ? RSQB_GN_Turned(a.FindInventory("RSQB_GN_Turned", true)) : null;\n\t\t\treturn t ? t.byPn : -1;', 'return -1;\t// the weapon sets: the frag only, nothing is turned', 1, f)
        if f == 'thrown':
            # x2 barrel damage (owner): each part of the blast hits barrels a second time, as hard
            t = _must(t, '\t\t\tif (part == 0) at.A_Explode(int(85 * dk + 0.5), int(200 * rk + 0.5), XF_HURTSOURCE);\n\t\t\telse at.A_Explode(int(75 * dk + 0.5), int(255 * rk + 0.5), XF_HURTSOURCE);',
                      '\t\t\tif (part == 0) { at.A_Explode(int(85 * dk + 0.5), int(200 * rk + 0.5), XF_HURTSOURCE); RSQB_GN_Kind.Barrels(at, int(85 * dk + 0.5), int(200 * rk + 0.5)); }\n'
                      '\t\t\telse { at.A_Explode(int(75 * dk + 0.5), int(255 * rk + 0.5), XF_HURTSOURCE); RSQB_GN_Kind.Barrels(at, int(75 * dk + 0.5), int(255 * rk + 0.5)); }\t// the weapon sets: barrels twice', 1, f)
        p = os.path.join(tree, 'zscript/rsqb/gn_%s.zs' % f); os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, 'w', encoding='latin-1').write(t); out.append('zscript/rsqb/gn_%s.zs' % f)
    # the lumps: cvars (renamed), the Quick Grenade key, the sounds it plays, the held and thrown models, the pickups
    cv = _gn(open(os.path.join(GN, 'CVARINFO.txt'), encoding='latin-1').read())
    # the frag only (owner: "don't give them the fancy alt fires"): no kinds, alt fire changes nothing
    cv = re.sub(r'(?m)^(\s*\w+\s+(?:noarchive\s+)?int\s+rsqb_gn_kinds_free\s*=\s*)\d+', r'\g<1>0', cv)
    cv = re.sub(r'(?m)^(\s*\w+\s+(?:noarchive\s+)?bool\s+rsqb_gn_kind_alt\s*=\s*)\w+', r'\g<1>false', cv)
    kc = ('// the weapon sets\' basic grenade (tools/lib/basics.py): RSQ Grenade\'s Quick Grenade\n'
          'alias rsqb_gn_quickthrow "netevent rsqb_gn_quick"\naddkeysection "Grenade" RSQBGrenade\naddmenukey "Quick Grenade" rsqb_gn_quickthrow\n')
    sn = open(os.path.join(GN, 'SNDINFO.txt'), encoding='latin-1').read()
    md = open(os.path.join(GN, 'MODELDEF.txt'), encoding='latin-1').read().replace('RSQGN_', 'RSQB_GN_')	# class names only: its files keep their names
    for d in ('models/rsqgn', 'sounds'):
        if os.path.isdir(os.path.join(GN, d)): shutil.copytree(os.path.join(GN, d), os.path.join(tree, d), dirs_exist_ok=True)
    for f in os.listdir(os.path.join(GN, 'sprites/rsqgn')):
        if f.upper().startswith(('QGN1', 'QGN3')):
            p = os.path.join(tree, 'sprites/rsqgn', f); os.makedirs(os.path.dirname(p), exist_ok=True)
            shutil.copyfile(os.path.join(GN, 'sprites/rsqgn', f), p)
    return out, {'CVARINFO.rsqbgn': cv, 'KEYCONF.rsqbgn': kc, 'SNDINFO.rsqbgn': sn, 'MODELDEF.rsqbgn': md}

def door(tree):
    t = open(os.path.join(DG, 'zscript/rsqdg/door.zs'), encoding='latin-1').read()
    t = t.replace('RSQDG_', 'RSQB_DG_')
    t = re.sub(r'\brsqdg_', 'rsqb_dg_', t)
    # stands down for Distance Grab (its own door does it)
    t = _must(t, '\toverride void WorldTick()\n\t{\n', '\toverride void WorldTick()\n\t{\n\t\tif (DGLoaded()) return;\t// the weapon sets: RSQ Distance Grab is loaded, its door lift is the one\n', 1, 'door')
    t = _must(t, '\toverride void NetworkProcess(ConsoleEvent e)\n\t{\n', '\tstatic bool DGLoaded() { return Object.FindClass("RSQDG_Door") != null; }\n\n\toverride void NetworkProcess(ConsoleEvent e)\n\t{\n\t\tif (DGLoaded()) return;\n', 1, 'door')
    t = '// GENERATED by tools/lib/basics.py from RSQ Distance Grab\'s zscript/rsqdg/door.zs (the weapon sets\' basic door lift)\n' + t
    p = os.path.join(tree, 'zscript/rsqb/door.zs'); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w', encoding='latin-1').write(t)
    return ['zscript/rsqb/door.zs']

