"""make_rsqtrfit.py: the Tactical Rig holster rows for this set's guns (owner 2026-11-16 03:30, review item 6).

RSQ Tactical Rig draws a stored gun on the body only when a lump named RSQTRFIT has a row for its class (TacticalRig
zscript/rsqtr/fit.zs: every RSQTRFIT in the load order is read, a later one wins for the same class). Its own table is
keyed to BD22's and vanilla Doom's class names, so this set ships its own: RSQTRFIT.wos, read only by the rig (nothing
else looks at it; without the rig it does nothing).

The rows are the rig's own measurement (TacticalRig/tools/measure_pickups.py --held: the model each gun is HELD as, its
Ready frame, from this set's own MODELDEFs and meshes), so each gun is drawn holstered as the same mesh it is held as.
The dump the tool keys on (PR <Class> <sprite lump> <frame>) is written here from each class's Ready state in src/
(the first frame of Ready), for every gun but the Knuckles (fists are not holstered) and every dual off-hand copy.

    python3 tools/make_rsqtrfit.py <the set's pk3>     -> RSQTRFIT.wos (in the set folder and in src/)"""
import glob, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
MEASURE = os.path.join(ROOT, '..', '..', 'TacticalRig', 'tools', 'measure_pickups.py')

def ready_frames():
    out, parent = {}, {}
    for p in sorted(glob.glob(os.path.join(ROOT, 'src/zscript/wos/*.zs'))):
        t = re.sub(r'//[^\n]*', '', open(p, encoding='latin-1').read())
        heads = list(re.finditer(r'^class\s+(\w+)\s*(?::\s*(\w+))?', t, re.M))
        for k, h in enumerate(heads):
            body = t[h.end():heads[k + 1].start() if k + 1 < len(heads) else len(t)]
            parent[h.group(1)] = h.group(2)
            m = re.search(r'^\s*Ready:\s*\n\s*"?([A-Z0-9_]{4})"?\s+"?([A-Z])"?\s', body, re.M)
            if m: out[h.group(1)] = (m.group(1), m.group(2))
    return out

def main():
    pk3 = sys.argv[1]
    R = ready_frames()
    guns = [c for c in R if c.startswith('RSQWS_') and c != 'RSQWS_Knuckles']
    dual = open(os.path.join(ROOT, 'zscript/wos/dual.gen.zs')).read() if os.path.exists(os.path.join(ROOT, 'zscript/wos/dual.gen.zs')) else ''
    offs = [(m.group(1), m.group(2)) for m in re.finditer(r'class (RSQ_Off_(\w+)) : \2', dual)]
    dump = os.path.join(ROOT, 'out', 'rsqtrfit_pr.txt'); os.makedirs(os.path.dirname(dump), exist_ok=True)
    with open(dump, 'w') as f:
        for c in guns:
            s, fr = R[c]; f.write('PR %s %s%s0 %d\n' % (c, s, fr, ord(fr) - 65))
        for off, base in offs:
            if base in R:
                s, fr = R[base]; f.write('PR %s %s%s0 %d\n' % (off, s, fr, ord(fr) - 65))
    raw = os.path.join(ROOT, 'out', 'RSQTRFIT.raw')
    subprocess.run([sys.executable, MEASURE, '--held', '--dump', dump, '--out', raw, pk3], check=True)
    rows = [l for l in open(raw).read().split('\n') if l and not l.startswith('//')]
    want = set(guns) | set(o for o, b in offs)
    got = set(l.split()[0] for l in rows)
    if want - got: raise SystemExit('no row measured for: %s' % ' '.join(sorted(want - got)))
    txt = ('// RSQTRFIT for RSQ Tactical Rig -- GENERATED by tools/make_rsqtrfit.py (TacticalRig/tools/measure_pickups.py --held on\n'
           '// this set\'s own pk3). Read only by the rig: each WoS gun drawn holstered as the mesh it is held as. Do not edit.\n'
           '// <Class> <length, map units> <yaw> <pitch> <shown by> <centre x y z> <squat> <sprite> <frame>\n') + '\n'.join(rows) + '\n'
    for p in (os.path.join(ROOT, 'RSQTRFIT.wos'), os.path.join(ROOT, 'src', 'RSQTRFIT.wos')):
        open(p, 'w').write(txt)
    print(txt)

if __name__ == '__main__':
    main()
