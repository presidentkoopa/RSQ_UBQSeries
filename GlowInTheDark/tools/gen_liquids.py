#!/usr/bin/env python3
"""gen_liquids.py -- writes zscript/rsqgd/liquids.zs from GLDEFS.txt (the owner's Glow list, Glow In The Dark 1.1).

    python GlowInTheDark/tools/gen_liquids.py

GLDEFS.txt is the one source of truth: the engine reads it to make those flats glow in their own colour, and
the ZScript reads the same names (through this generated file) to know which floors and ceilings are liquids,
so the Liquids switch can turn exactly those off. Edit GLDEFS.txt, then run this. Never edit liquids.zs."""
import os, re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, 'GLDEFS.txt')
OUT = os.path.join(HERE, 'zscript', 'rsqgd', 'liquids.zs')

text = open(SRC, encoding='latin-1').read()
text = re.sub(r'//[^\n]*', '', text)
names = []
for block in ('Flats', 'Walls'):
    m = re.search(r'\b' + block + r'\s*\{([^}]*)\}', text, re.I)
    if not m:
        raise SystemExit('no %s block in GLDEFS.txt' % block)
    for tok in m.group(1).split():
        t = tok.strip().upper()
        if t and t not in names:
            names.append(t)

lines = ['// GENERATED by tools/gen_liquids.py from GLDEFS.txt (the owner\'s Glow list). Do not edit: edit GLDEFS.txt',
         '// and run the tool. %d names (Flats and Walls blocks, duplicates dropped).' % len(names),
         '',
         'class RSQGD_LiquidNames',
         '{',
         '\t// the list lives in a function (a class-level const array is not reachable from functions on QZD 17.3)',
         '\tstatic void Fill(Array<String> dst)',
         '\t{',
         '\t\tstatic const String NAMES[] =',
         '\t\t{']
row = []
for n in names:
    row.append('"%s"' % n)
    if len(row) == 10:
        lines.append('\t\t\t' + ', '.join(row) + ',')
        row = []
if row:
    lines.append('\t\t\t' + ', '.join(row))
else:
    lines[-1] = lines[-1].rstrip(',')
lines += ['\t\t};', '\t\tfor (int i = 0; i < NAMES.Size(); i++) dst.Push(NAMES[i]);', '\t}', '}', '']
open(OUT, 'w', newline='\n').write('\n'.join(lines))
print('wrote %s (%d names)' % (os.path.relpath(OUT, HERE), len(names)))
