"""hitsensor_gen.py -- writes zscript/rsscore/hitsensor_cards.zs, the per-class table the hit sensors read.

One row per XMVE head / leg helper class (HeadshotTarget*, LegTarget*: design/GORE_SYSTEM_DESIGN.md section 3 option C,
section 9's exact list): its kind, box, health and lifetime, read from Brutal Doom 22's DECORATE and XMVE's pk3.
Never hand-edit the output; rerun this and then tools/hitsensor_lint.py.

    python -I tools/hitsensor_gen.py [--bd <BD22 src folder>] [--xmve <XMVE pk3>]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hitsensor_dec as dec  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "zscript", "rsscore", "hitsensor_cards.zs")


def rows(bd, xmve):
    actors = dec.read_sources(bd, xmve)
    head, leg, other = dec.helpers(actors)
    spawned = dec.spawned_helper_names(xmve)
    out = []
    for kind, keys in ((1, head), (2, leg)):
        for k in keys:
            props, factors, flags, life, loops = dec.resolved(actors, k)
            out.append({
                "name": actors[k].name, "kind": kind, "origin": actors[k].origin,
                "radius": float(props.get("radius", "0")), "height": float(props.get("height", "0")),
                "health": int(props.get("health", "1000")), "life": life, "loops": loops,
                "calls": spawned.get(k, 0),
            })
    return out, other, actors


def render(out, other):
    n = len(out)
    names = ", ".join('"%s"' % r["name"] for r in out)
    kinds = ", ".join(str(r["kind"]) for r in out)
    lives = ", ".join(str(r["life"]) for r in out)
    radii = ", ".join("%g" % r["radius"] for r in out)
    heights = ", ".join("%g" % r["height"] for r in out)
    healths = ", ".join(str(r["health"]) for r in out)
    lines = [
        "// GENERATED by tools/hitsensor_gen.py from Brutal Doom 22's DECORATE and XMVE's pk3 -- never hand-edit; rerun it,",
        "// then tools/hitsensor_lint.py. The hit sensors' per-class table (hitsensor.zs; design/GORE_SYSTEM_DESIGN.md 3, 9).",
        "//",
        "// kind 1 head (HeadshotTargetBase: any pain ends in A_Explode(20, 15, 0, 0, 15) of type head), 2 leg (LegTargetBase:",
        "// its health ladder, 2-400 \"leg\"). life = its Spawn state's tics to Stop: how long XMVE's helper would have stood.",
        "// Not helpers, left alone (`is` HeadshotTargetBase / LegTargetBase but not named as helpers): " + ", ".join(other),
        "//",
        "//   class                kind  radius height  health  life  XMVE calls  from",
    ]
    for r in out:
        lines.append("//   %-20s %4d  %6g %6g  %6d  %4d  %10d  %s" % (r["name"], r["kind"], r["radius"], r["height"],
                                                                     r["health"], r["life"], r["calls"], r["origin"]))
    lines += [
        "",
        "class RS_ScoreHitCards",
        "{",
        "\tstatic int Count() { return %d; }" % n,
        "\tstatic String NameAt(int i) { static const String V[] = { %s }; return (i >= 0 && i < V.Size()) ? V[i] : \"\"; }" % names,
        "\tstatic int KindAt(int i) { static const int V[] = { %s }; return (i >= 0 && i < V.Size()) ? V[i] : 0; }" % kinds,
        "\tstatic int LifeAt(int i) { static const int V[] = { %s }; return (i >= 0 && i < V.Size()) ? V[i] : 0; }" % lives,
        "\tstatic double RadiusAt(int i) { static const double V[] = { %s }; return (i >= 0 && i < V.Size()) ? V[i] : 0; }" % radii,
        "\tstatic double HeightAt(int i) { static const double V[] = { %s }; return (i >= 0 && i < V.Size()) ? V[i] : 0; }" % heights,
        "\tstatic int HealthAt(int i) { static const int V[] = { %s }; return (i >= 0 && i < V.Size()) ? V[i] : 0; }" % healths,
        "}",
        "",
        "// One declaration class per helper: CheckReplacement swaps a helper for its own, so the declaration knows its row.",
    ]
    for i, r in enumerate(out):
        lines.append("class RS_ScoreHitDecl_%s : RS_ScoreHitDecl { override int Card() { return %d; } }" % (r["name"], i))
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bd", default=dec.BD_SRC)
    ap.add_argument("--xmve", default=dec.XMVE_PK3)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true", help="only report whether the file on disk is current")
    a = ap.parse_args()
    out, other, _ = rows(a.bd, a.xmve)
    bad = [r["name"] for r in out if r["life"] is None or r["loops"] or r["life"] <= 0]
    if bad:
        print("hitsensor_gen: no plain Spawn-to-Stop life for " + ", ".join(bad))
        return 1
    text = render(out, other)
    if a.check:
        cur = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else ""
        print("current" if cur == text else "STALE")
        return 0 if cur == text else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("hitsensor_gen: %d classes (%d head, %d leg) -> %s" % (len(out), sum(r["kind"] == 1 for r in out),
                                                               sum(r["kind"] == 2 for r in out), os.path.normpath(a.out)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
