# TEST ONLY: P2E launch (rig02, RES 120, no frames): A2 (which off hand the saber gets; the Force Pull gates), H2, D2, D1.
import sys; sys.path.insert(0, '.')
from lib import S
s = S()
REST_R = (0.25, 1.30, -0.30); REST_L = (-0.25, 1.30, -0.30)
s.add('wait 20', 'vr_control_scheme 0', 'bd_tips 0', 'crosshair 0', 'screenblocks 10', 'buddha', 'set ssq_debug 1', 'set ubqs_diag 4',
      'set rsqdg_debug 1', 'set rsqdg_trace 1', 'set rsqdg_corpses 1', 'qz_hmd "0 1.6 0 0 0 0"', 'rsqml_gloves', 'rsqml_slappers', 'ubqs_force_saber', 'ubqs_force_hand')
s.r(*REST_R); s.l(*REST_L); s.w(20); s.add('netevent p2_clearmon', 'netevent p2_off 0')
s.add('echo A2_SABER_IN', 'use UBQS_Saber'); s.w(70); s.add('netevent p2_off 1', 'netevent p2_item:Medikit 200 0'); s.w(5); s.add('netevent p2_force 0')
def yank(tag):
    s.l(-0.25, 1.30, -0.55, -10); s.w(10); s.add('qz_ltrigger 1', '+oh_altatk'); s.w(10)
    for z in (-0.55, -0.46, -0.37, -0.28, -0.19): s.l(-0.25, 1.30, z, -10); s.w(1)
    s.w(2); s.add('netevent p2_force %d' % tag, 'qz_ltrigger 0', '-oh_altatk'); s.w(30); s.add('netevent p2_force %d' % (tag + 1)); s.l(*REST_L); s.w(10)
s.add('echo A2_GLOVE_OFFHAND'); yank(5)
s.add('echo A2_FORCEHAND_SELECTED', 'use UBQS_ForceHand'); s.w(40); s.add('netevent p2_off 2')
s.add('echo A2_NOT_FORCE_SENSITIVE'); yank(10)
s.add('echo A2_ADD_ALL', 'netevent rsqgb_dbg_all'); s.w(60); s.add('netevent p2_off 3', 'set ubqs_force 0'); s.w(40); s.add('netevent p2_force 19', 'netevent p2_off 19')
s.add('echo A2_FORCE_OFF'); yank(20)
s.add('set ubqs_force 1', 'netevent p2_hp 50'); s.w(40); s.add('netevent p2_force 29', 'netevent p2_off 29')
s.add('echo A2_CONTROL_FORCE_ON_LEARNED'); yank(30); s.w(30); s.add('netevent p2_force 32', 'netevent p2_items', 'netevent p2_hp 100', 'netevent p2_off 33')
# ---- H2: a gun in the main hand (no lit blade in the bullet's way), the plate facing forward
s.add('echo H2', 'netevent p2_del 0', 'netevent p2_tp -320 0 0', 'give SSQ_ShieldSaw', 'give Shot_Gun'); s.w(2); s.add('use Shot_Gun'); s.w(60)
s.add('netevent p2_ssqset 1', 'set ssq_hitscan_guard 0'); s.l(-0.05, 1.15, -0.30, 0, -90, 0); s.w(40); s.add('netevent p2_ssq 10', 'netevent p2_off 10')
s.add('netevent p2_zm 400 0'); s.w(10)
s.add('echo H2_FAR_LINEATTACK', 'netevent p2_hp 100', 'netevent p2_zshoot 0'); s.w(10)
s.add('echo H2_FAR_INFLICTOR_IS_SHOOTER', 'netevent p2_hp 100', 'netevent p2_zhit'); s.w(10)
s.add('echo H2_FAR_MUZZLE_ON', 'set ssq_hitscan_guard 1', 'netevent p2_hp 100'); s.w(3); s.add('netevent p2_zshoot 0'); s.w(10)
s.add('set ssq_hitscan_guard 0', 'netevent p2_zclear', 'netevent p2_zm 50 0'); s.w(10)
s.add('echo H2_NEAR_INFLICTOR_IS_SHOOTER', 'netevent p2_hp 100', 'netevent p2_zhit'); s.w(10)
s.add('netevent p2_zclear', 'set ssq_hitscan_guard 1'); s.l(*REST_L); s.w(5); s.add('netevent p2_ssqset 0'); s.w(30)
# ---- D2 with a lock: the palm NOT out (roll 0), pitch tried two ways
s.add('echo D', 'netevent p2_clearfloor', 'netevent p2_tp -320 0 0', 'netevent p2_item:ExplosiveBarrel 160 0'); s.w(5); s.add('netevent p2_off 50')
s.add('echo D2_PALMGATE_OFF_KEYS_OFF', 'set rsqdg_palm 0', 'set rsqdg_button 0')
for p in (-11, 19, -41): s.r(0.25, 1.30, -0.30, p, 0, 0); s.w(15)
s.add('echo D2_PALMGATE_OFF_KEYS_ON', 'set rsqdg_button 1')
for p in (-11, 19, -41): s.add('echo D2_PITCH_%d' % p); s.r(0.25, 1.30, -0.30, p, 0, 0); s.w(15)
s.add('echo D2_KEY_PRESS_RELEASE', '+rsqdg_main'); s.w(3); s.add('-rsqdg_main'); s.w(20)
s.add('echo D2_PALMGATE_ON_KEYS_OFF', 'set rsqdg_button 0', 'set rsqdg_palm 1')
for p in (-11, 19, -41): s.r(0.25, 1.30, -0.30, p, 0, 0); s.w(15)
# ---- D1 a heavy throw: the 100 kg corpse, nothing else in the cone
s.add('echo D1_CORPSE', 'netevent p2_del 3', 'netevent p2_item:ZombieMan 160 0'); s.w(10); s.add('netevent p2_kill 4'); s.w(70); s.add('netevent p2_clearfloor', 'netevent p2_items')
s.r(0.25, 1.30, -0.30, -11, -30, 90); s.w(30)
s.r(0.25, 1.30, -0.30, 2, -30, 90); s.w(2); s.r(0.25, 1.30, -0.30, 15, -30, 90); s.w(2); s.r(0.25, 1.30, -0.30, 15, -30, 0); s.w(4)
s.r(0.25, 1.30, -0.30, -11, -30, 90); s.w(60); s.add('netevent p2_items', 'qz_rgrip 1'); s.w(5); s.r(0.25, 1.30, -0.30, -11, -30, 0); s.w(5)
for k in range(10): s.r(0.25, 1.25 + 0.01 * k, -0.30 + 0.025 * k, -11, -30, 0); s.w(1)
for k in range(7):
    s.r(0.25, 1.35 + 0.03 * k, -0.05 - 0.30 * k, -11, -30, 0)
    if k == 4: s.add('qz_rgrip 0')
    s.w(1)
s.r(0.25, 1.30, -0.40, -11, -30, 0); s.w(10); s.add('netevent p2_dgkg', 'netevent p2_items'); s.w(60); s.add('netevent p2_dgkg', 'netevent p2_items')
s.add('echo P2E_END'); s.w(5); s.add('quit')
open(sys.argv[1], 'w').write(s.text()); print(len(s.c), 'commands')
