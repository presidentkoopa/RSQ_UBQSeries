#!/usr/bin/env python3
"""Writes Monsters/zscript/monsters/RS_BDTierData.zs from data/family_curves.csv, data/bd_xmve_ladders.csv
and data/bd22.json (the family base HP). Run from the repo root: python3 design/tiering/tools/gen_zs.py
The tables are the PROPOSAL of design/BD_XMVE_TIERING.md sections 3 and 5; change the CSVs, not the .zs."""
import csv, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, '..', 'data')
OUT = os.path.join(HERE, '..', '..', '..', 'Monsters', 'zscript', 'monsters', 'RS_BDTierData.zs')
# RS_RosterHandler.FamilyId's order
FAM = ['Zombieman', 'Shotgunner', 'Chaingunner', 'Imp', 'Demon', 'Spectre', 'Cacodemon', 'Lost Soul', 'Pain Elemental',
       'Hell Knight', 'Baron', 'Revenant', 'Mancubus', 'Arachnotron', 'Arch-Vile', 'Cyberdemon', 'Spider Mastermind']
BASE = {'riflezombie': 'Zombieman', 'shotgunguy1': 'Shotgunner', 'chaingunguy1': 'Chaingunner', 'imp': 'Imp',
        'bulldemon': 'Demon', 'spectro': 'Spectre', 'cacodemon_': 'Cacodemon', 'tehlostsoul': 'Lost Soul',
        'painelemental1': 'Pain Elemental', 'hellknight2': 'Hell Knight', 'baronofhell2': 'Baron',
        'revenant1': 'Revenant', 'mancubus': 'Mancubus', 'arachnotron1': 'Arachnotron', 'teharchvile': 'Arch-Vile',
        'thecyberdemon': 'Cyberdemon', 'thespidermastermind': 'Spider Mastermind'}
# design 5: ACS health-bar bosses get the HP curve only, no kit
HPONLY = {'CyberdemonBoss': 'Cyberdemon', 'GreatCyberdemon': 'Cyberdemon', 'SuperMastermind': 'Spider Mastermind'}
# THE OWNER'S ORDER (2026-11-13 09:57, 10:00: "0 is neutral, 1 is green, etc ... i told you what my order is"): every
# monster as its mod ships it is the neutral step; no monster starts higher because it is stronger. So every row's
# entry colour is 1 (Common). The CSV's "entry tier" column is the design's earlier proposal and is no longer used.
ENTRY = 1
cur = {}
for r in csv.reader(open(os.path.join(D, 'family_curves.csv'))):
    if r[0] == 'family': continue
    cur.setdefault(r[0], {})[r[1]] = [float(x) for x in r[2:]]
bd = {r['name'].lower(): r for r in json.load(open(os.path.join(D, 'bd22.json')))}
basehp = {BASE[k]: int(bd[k]['health']) for k in BASE}
rows = list(csv.DictReader(open(os.path.join(D, 'bd_xmve_ladders.csv'))))

def arr(name, typ, vals, per=13):
    s = f"\t\tstatic const {typ} {name}[] = {{\n"
    for i in range(0, len(vals), per):
        s += "\t\t\t" + ", ".join(str(v) for v in vals[i:i + per]) + ("," if i + per < len(vals) else "") + "\n"
    return s + "\t\t};\n"

o = []
o.append("// GENERATED by design/tiering/tools/gen_zs.py from design/tiering/data. DO NOT EDIT BY HAND: change the CSVs and re-run.\n"
         "// The numbers are the PROPOSAL of design/BD_XMVE_TIERING.md (sections 3 and 5). Families in RS_RosterHandler.FamilyId's order.\n")
o.append("class RS_BDTierData\n{\n")
for fn, row in (('HP', 'HP mult (proposal)'), ('Spd', 'speed mult'), ('Pain', 'painchance mult')):
    vals = []
    for f in FAM: vals += cur[f][row]
    o.append(f"\tstatic double {fn}(int fam, int tier)\n\t{{\n" + arr('T', 'double', vals) +
             "\t\tif (fam < 0 || fam > 16) return 1.0;\n\t\treturn T[fam * 13 + clamp(tier, 1, 13) - 1];\n\t}\n\n")
o.append("\tstatic double Dmg(int tier)\n\t{\n" + arr('T', 'double', cur['ALL']['damage mult (proposal)']) +
         "\t\treturn T[clamp(tier, 1, 13) - 1];\n\t}\n\n")
o.append("\t// Brutal Doom 22's own health for each family's base monster (design/tiering/data/bd22.json)\n"
         "\tstatic int BDBaseHP(int fam)\n\t{\n" + arr('T', 'int', [basehp[f] for f in FAM], 17) +
         "\t\treturn (fam < 0 || fam > 16) ? 0 : T[fam];\n\t}\n\n")
ent = []
seen = set()
for r in rows:
    c = r['class']
    if c.lower() in seen: continue
    seen.add(c.lower())
    if r['entry tier'] == 'exempt': ent.append(f'"{c}:-1:0:0"'); continue
    if r['family'] not in FAM: continue
    ent.append(f'"{c}:{FAM.index(r["family"])}:{ENTRY}:0"')
# Monsters of the other mods in the owner's load order that no parent or replacement chain leads to a family (found
# on the rig 2026-11-13 with `netevent rs_bdtier_classes`, his full order). Legion of Bones' own monsters (its spawners
# lose to XMVE's in his order, so today they only come from maps that place them); the Wolfenstein SS slot (BD's Nazi is
# in the zombie family); EvilMarine, the SS slot's spawner, which is gone a tic later; Keen and LoB's decoys: exempt.
EXTRA = [('DragonSoul', 'Lost Soul'), ('HotHead', 'Lost Soul'), ('ReaperBloodSkull', 'Lost Soul'), ('SlayerKnight', 'Hell Knight'),
         ('CacoLich', 'Cacodemon'), ('PhantomRevenant2', 'Revenant'), ('RetroSkeleton', 'Zombieman'),
         ('WolfensteinSS', 'Zombieman'), ('EvilMarine', None), ('CommanderKeen', None), ('FakeGhostSpectre', None),
         ('ConqCube', None),
         # Brutal Doom's own non-monsters that carry MONSTER and count as kills: 1-health helpers, a critter, the tank
         # hulls (99999), the friendly dogs, and a last stand (a death stage: the body's tint follows it, no kit)
         ('RevenantMissileFriendAttackSummon', None), ('MonsterSightAlert', None), ('LiveSkull', None),
         ('BDCritterMouse', None), ('ZombieMainBattleTankBody1', None), ('ZombieArtilleryTankBody1', None),
         ('MBFHelperDog', None), ('BrutalMBFHelperDog', None), ('HelmetSergeantLastStand2', None)]
for c, f in EXTRA:
    if any(x.lower().startswith('"' + c.lower() + ':') for x in ent): continue
    ent.append(f'"{c}:-1:0:0"' if f is None else f'"{c}:{FAM.index(f)}:{ENTRY}:0"')
for c, f in HPONLY.items():
    ent = [x for x in ent if not x.lower().startswith('"' + c.lower() + ':')]
    ent.append(f'"{c}:{FAM.index(f)}:{ENTRY}:1"')
o.append("\t// class : family : entry colour (always 1: the owner's order, every monster as shipped is the neutral step) :\n"
         "\t// 1 = health curve only (an ACS health-bar boss). Family -1 = exempt (a scripted map piece).\n"
         "\tstatic int RowCount() { return %d; }\n\tstatic String Row(int i)\n\t{\n" % len(ent) + arr('T', 'String', ent, 4) +
         "\t\treturn T[i];\n\t}\n}\n")
# fix 4 (design 8.4): ladder health. hp_drops.json "envelope": family (RS_TierLadder's numbering) : colour -> the
# family's running maximum, +5% a step. 0 = keep the class's own health (the two KEEP verdicts).
env = json.load(open(os.path.join(D, 'hp_drops.json')))['envelope']
KEEP = {(5, 9), (16, 5)}   # the Gray Lost Soul hive; the Cyan Zombie (three bodies)
ev = []
for f in range(17):
    for t in range(1, 14):
        v = env.get('%d:%d' % (f, t), 0)
        ev.append(0 if (f, t) in KEEP or t > 11 else int(v))
o[-1] = o[-1].rstrip()[:-1].rstrip() + "\n\n"
o.append("\t// LADDER HEALTH (design/BD_XMVE_TIERING.md 8.4): a ColorfulHell colour's health under a tier change or a world tier\n"
         "\t// above 1, so that no step up the ladder loses health. Family in RS_TierLadder's numbering. 0 = the class's own\n"
         "\t// (Black and White, and the two the design keeps: the Gray Lost Soul hive, the Cyan Zombie's three bodies).\n"
         "\tstatic int Envelope(int fam, int tier)\n\t{\n" + arr('T', 'int', ev) +
         "\t\tif (fam < 0 || fam > 16 || tier < 1 || tier > 13) return 0;\n\t\treturn T[fam * 13 + tier - 1];\n\t}\n}\n")
open(OUT, 'w').write("".join(o))
print("wrote", os.path.normpath(OUT), len(ent), "rows; base HP", basehp)
