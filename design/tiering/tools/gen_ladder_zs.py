#!/usr/bin/env python3
"""Writes Monsters/zscript/monsters/RS_LadderData.zs for the ladder system (design/LADDER_SYSTEM.md).
Run from anywhere: python3 design/tiering/tools/gen_ladder_zs.py
Sources (never typed by hand, rule 4):
  data/ch_ladder.csv         ColorfulHell health per family per colour
  data/hp_drops.json         "envelope": ladder health, the family's running maximum x1.05 a step (point 5)
  data/hp_drops_verdicts.csv the two steps the proposal KEEPS at ColorfulHell's own health
Rungs: 1-11 Common..Abyss (ladder health), 12 Black = Abyss x1.25, 13 White = Abyss x1.5 (point 2, boss-grade),
14 EX = White x1.1 (point 3: EX is its own step above White)."""
import csv, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, '..', 'data')
OUT = os.path.join(HERE, '..', '..', '..', 'Monsters', 'zscript', 'monsters', 'RS_LadderData.zs')
# RS_RosterHandler.FamilyId's order
FAM = ['Zombieman', 'Shotgunner', 'Chaingunner', 'Imp', 'Demon', 'Spectre', 'Cacodemon', 'Lost Soul', 'Pain Elemental',
       'Hell Knight', 'Baron', 'Revenant', 'Mancubus', 'Arachnotron', 'Arch-Vile', 'Cyberdemon', 'Spider Mastermind']
COL = ['Common', 'Green', 'Blue', 'Purple', 'Cyan', 'Brown', 'Yellow', 'FireBlu', 'Gray', 'Red', 'Abyss', 'Black', 'White']
# The EX build of each family (class names from the Monsters code); '' = the family has none: its EX rung is White, x1.1
EX = {'Zombieman': 'RS_BlackZombieEX', 'Shotgunner': 'RS_WhiteSGEX', 'Chaingunner': 'RS_BlackCGuyEX',
      'Imp': 'RS_BlackImpEX', 'Cacodemon': 'RS_BlackCacoEX', 'Lost Soul': 'RS_WhiteLSoulEX', 'Hell Knight': 'RS_BlackHKEX',
      'Revenant': 'RS_BlackRevenantEX', 'Mancubus': 'RS_BlackFatsoEX', 'Arachnotron': 'RS_BlackSPEX'}

raw, order = {}, []
for r in csv.DictReader(open(os.path.join(D, 'ch_ladder.csv'))):
    if r['family'] not in order: order.append(r['family'])
    raw[(r['family'], r['colour'])] = int(float(r['health']))
env = json.load(open(os.path.join(D, 'hp_drops.json')))['envelope']     # "<ch_ladder family index>:<tier>"
keep = set()
for r in csv.DictReader(open(os.path.join(D, 'hp_drops_verdicts.csv'))):
    if r['verdict'].startswith('KEEP'): keep.add((r['family'], r['to']))

hp = []
for f in FAM:
    fi = order.index(f)
    row = []
    for t in range(1, 12):
        c = COL[t - 1]
        row.append(raw[(f, c)] if (f, c) in keep else int(env[f'{fi}:{t}']))
    ab = int(env[f'{fi}:11'])
    row += [round(ab * 1.25), round(ab * 1.5), round(ab * 1.5 * 1.1)]
    hp.append(row)

def arr(name, typ, vals, per):
    s = f"\t\tstatic const {typ} {name}[] = {{\n"
    for i in range(0, len(vals), per):
        s += "\t\t\t" + ", ".join(str(v) for v in vals[i:i + per]) + ("," if i + per < len(vals) else "") + "\n"
    return s + "\t\t};\n"

o = ["// GENERATED by design/tiering/tools/gen_ladder_zs.py. DO NOT EDIT BY HAND: change the data and re-run.\n"
     "// The ladder system (design/LADDER_SYSTEM.md), points 2, 3 and 5. Families in RS_RosterHandler.FamilyId's order.\n"
     "class RS_LadderData\n{\n"]
flat = [v for row in hp for v in row]
o.append("\t// Health a ColorfulHell monster has under the ladder system, rung 1-14 (before the skill's MonsterHealth).\n"
         "\t// 1-11 ladder health (point 5; two steps kept at ColorfulHell's own), 12 Black and 13 White boss-grade (point 2),\n"
         "\t// 14 EX (point 3).\n"
         "\tstatic int HP(int fam, int rung)\n\t{\n" + arr('T', 'int', flat, 14) +
         "\t\tif (fam < 0 || fam > 16) return 0;\n\t\treturn T[fam * 14 + clamp(rung, 1, 14) - 1];\n\t}\n\n")
o.append("\t// The family's EX build, or 'None' (its EX rung is White).\n"
         "\tstatic Name EXClass(int fam)\n\t{\n" +
         arr('T', 'Name', ["'%s'" % (EX.get(f) or 'None') for f in FAM], 6) +
         "\t\treturn (fam < 0 || fam > 16) ? 'None' : T[fam];\n\t}\n}\n")
open(OUT, 'w').write("".join(o))
print("wrote", os.path.normpath(OUT))
for f, row in zip(FAM, hp): print(f"{f:18s}", row)
print("kept:", sorted(keep))
