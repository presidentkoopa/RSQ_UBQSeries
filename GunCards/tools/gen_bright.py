"""gen_bright.py -- the cards' GLOW twins (owner 2026-11-06, BUGS_1.0 #19: "could these get any kind of emissive glow
or light on a kind of Quest / PCVR setting").

A HUD model is lit by the sector the player stands in unless its state is Bright. The generated card states
(card_states.zs, side_states.zs, from gen_cards.py / gen_side.py) are not Bright, so this makes a twin of each with
every frame Bright: RSQGC_CardStatesB, RSQGC_SideStatesB (same labels, same voxels, nothing new baked). card.zs picks
the twin while Card Glow is on (Quest: the cards are fullbright; PCVR: the same, plus a small dynamic light at the hand).

Run after gen_cards.py / gen_side.py: python GunCards/tools/gen_bright.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ZS = os.path.join(os.path.dirname(HERE), 'zscript', 'rsqgc')
FRAME = re.compile(r'^(\t\t[A-Z0-9]{4} [A-Z\[\]\\^]+ -?\d+);$')

for src, cls in (('card_states.zs', 'RSQGC_CardStates'), ('side_states.zs', 'RSQGC_SideStates')):
    lines = open(os.path.join(ZS, src)).read().split('\n')
    out, n = [], 0
    for ln in lines:
        m = FRAME.match(ln)
        if m:
            ln = m.group(1) + ' Bright;'
            n += 1
        out.append(ln)
    s = '\n'.join(out)
    s = s.replace('class %s : Weapon' % cls, 'class %sB : Weapon' % cls, 1)
    s = s.replace('GetDefaultByType("%s")' % cls, 'GetDefaultByType("%sB")' % cls)
    s = ('// GENERATED by tools/gen_bright.py from %s -- do not edit. Its Bright twin (Card Glow).\n' % src) + s
    dst = src.replace('.zs', '_b.zs')
    open(os.path.join(ZS, dst), 'w').write(s)
    print('%s -> %s (%d frames Bright)' % (src, dst, n))
