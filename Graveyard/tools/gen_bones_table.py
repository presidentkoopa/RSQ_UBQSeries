#!/usr/bin/env python3
"""gen_bones_table.py -- RSQ Graveyards' Bones Bridge table: which Brutal Doom / XMVE monster stands in for which of the 13
vanilla monsters Legion of Bones raises, read from the packs' own DECORATE (parsed, nothing guessed).

    python3 -I Graveyard/tools/gen_bones_table.py <brutal22test6.pk3> <XMVE 04 pk3> <XMVE 06 pk3> [more pk3s]

A class goes in the table when (a) it REPLACES one of the 13 (BD's RifleZombie replaces ZombieMan, XMVE's ZombiemanSpawner
replaces ZombieMan), (b) an XMVE spawner that replaces one of the 13 (a class named *Spawner) spawns it, unless that class
itself replaces something Legion of Bones does not raise (PainElemental1 replaces PainElemental: it stays dead), or (c) it
is BD's classic stand-in (Vanilla*) spawned by a class in the table. At run time (zscript/rsqgy/bones.zs) a dead monster's
class and each of its parents are looked up, so subclasses (BD's stealth and nightmare kinds, XMVE's stealth kinds) follow
their parent. EXCLUDED: BD's death helpers that inherit a table class (a crawling half-dead zombie, a cast-call actor): the
monster already died once and rises once. Writes Graveyard/zscript/rsqgy/bones_table.zs.
"""
import re, sys, os, zipfile
V = ["ZombieMan", "ShotgunGuy", "ChaingunGuy", "DoomImp", "Demon", "Spectre", "Cacodemon", "HellKnight", "BaronOfHell",
     "Revenant", "Fatso", "Arachnotron", "Archvile"]
OTHER = {"lostsoul", "painelemental", "cyberdemon", "spidermastermind", "wolfensteinss", "commanderkeen", "bossbrain"}
HELPER = re.compile(r'(dying|losthis|armless|cast$|brutalized|laststand|gothisleg|burning|falling|sacilol|headshot|hitbox|bloodloss|hitineye|lostteeth|noarm|noleg|nohead)', re.I)
VL = {v.lower(): i for i, v in enumerate(V)}
hdr = re.compile(r'^\s*actor\s+([\w.]+)\s*(?::\s*([\w.]+))?\s*(?:replaces\s+([\w.]+))?', re.I)
blocks = {}
for pk in sys.argv[1:]:
    z = zipfile.ZipFile(pk)
    for n in sorted(z.namelist()):
        if n.endswith('/') or re.search(r'\.(png|ogg|wav|flac|mp3|md3|md2|dmd|kvx|wad|o|lmp|jpg|tga|iqm|obj|pcx|fp|vp)$', n, re.I):
            continue
        t = z.read(n).decode('latin-1')
        if not re.search(r'^\s*actor\s', t, re.I | re.M):
            continue
        t = re.sub(r'//[^\n]*', '', t); t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
        cur = None
        for ln in t.split('\n'):
            m = hdr.match(ln)
            if m:
                cur = m.group(1).lower()
                blocks[cur] = [m.group(2).lower() if m.group(2) else None, m.group(3).lower() if m.group(3) else None, '', m.group(1)]
                continue
            if cur:
                blocks[cur][2] += ln + '\n'
res, why = {}, {}
for n, b in blocks.items():
    if b[1] in VL:
        res[n] = VL[b[1]]; why[n] = 'replaces ' + V[VL[b[1]]]
for n, b in list(blocks.items()):
    if not n.endswith('spawner') or n not in res:
        continue
    for s in re.findall(r'A_SpawnItem(?:Ex)?\s*\(\s*"([\w.]+)"', b[2], re.I):
        s = s.lower()
        if s in blocks and s not in res and blocks[s][1] not in OTHER:
            res[s] = res[n]; why[s] = 'XMVE ' + b[3]
for n in list(res):
    for s in re.findall(r'A_SpawnItem(?:Ex)?\s*\(\s*"(Vanilla[\w.]*)"', blocks[n][2], re.I):
        s = s.lower()
        if s in blocks and s not in res:
            res[s] = res[n]; why[s] = 'BD classic stand-in of ' + blocks[n][3]
def chain(n):
    out = []
    while n and len(out) < 30:
        out.append(n); n = blocks[n][0] if n in blocks else None
    return out
excl = sorted(blocks[n][3] for n in blocks if n not in res and HELPER.search(n) and any(x in res or x in VL for x in chain(n)[1:]))
order = sorted(res, key=lambda k: (res[k], k))
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'zscript', 'rsqgy', 'bones_table.zs')
with open(out, 'w') as f:
    f.write('// GENERATED by Graveyard/tools/gen_bones_table.py from %s -- do not edit by hand.\n' % ', '.join(os.path.basename(p) for p in sys.argv[1:]))
    f.write('// The Bones Bridge table: a Brutal Doom / XMVE class -> the vanilla monster it stands in for (index into gy_Bones.VANILLA).\n')
    f.write('class gy_BonesTable play\n{\n')
    f.write('\t// the vanilla monster (0..12, gy_Bones.Vanilla) a class stands in for, -1 not in the table\n')
    f.write('\tstatic int Kind(Name cn)\n\t{\n')
    f.write('\t\tstatic const Name CLS[] = {\n' + ',\n'.join('\t\t\t\'%s\'' % blocks[n][3] for n in order) + '\n\t\t};\n')
    f.write('\t\tstatic const int KIND[] = {\n' + '\n'.join('\t\t\t%d%s\t// %s %s' % (res[n], ',' if i < len(order) - 1 else ' ', blocks[n][3], why[n]) for i, n in enumerate(order)) + '\n\t\t};\n')
    f.write('\t\tfor (int i = 0; i < CLS.Size(); i++) if (cn == CLS[i]) return KIND[i];\n\t\treturn -1;\n\t}\n')
    f.write('\t// death helpers that inherit a table class: they never rise (the monster already died once)\n')
    f.write('\tstatic bool Never(Name cn)\n\t{\n')
    f.write('\t\tstatic const Name NEVER[] = {\n' + ',\n'.join('\t\t\t\'%s\'' % e for e in excl) + '\n\t\t};\n')
    f.write('\t\tfor (int i = 0; i < NEVER.Size(); i++) if (cn == NEVER[i]) return true;\n\t\treturn false;\n\t}\n}\n')
print('%d classes, %d helpers excluded -> %s' % (len(order), len(excl), out))
for k in range(len(V)):
    print('  %-12s %s' % (V[k], ', '.join(blocks[n][3] for n in order if res[n] == k)))
