# gen_ldlite.py <LegenDoomLite.pk3 extracted dir> <Miniboss dir>
# Builds RSQ Miniboss's copy of Yholl's LegenDoom Lite from his files (Miniboss/tools/gen_ldlite.py keeps this script).
# Kept: every class name (so every RSQ mod, Champions and BD22 VR see its legendaries by LegenDoom's names), his DECORATE.
# Changed: his ACS (not built here) -> ZScript (zscript/rsqmb/ldlite.zs) through RSQLDL_* functions on two ZScript bases;
# his LD_* cvars -> rsqmb_ldl_*; his menu ids and LANGUAGE ids -> RSQMB_LDL*; the boss transform sound -> rsqmb/ldl/boss
# (LDLEBOSS differs from LegenDoom's); the afterimages' Light() calls removed: ldlite.zs puts one of his lights on the monster.
import os, re, sys, shutil
S, M = sys.argv[1], sys.argv[2]
def rd(p): return open(os.path.join(S, p), encoding='latin-1').read()
def wr(p, t):
    p = os.path.join(M, p); os.makedirs(os.path.dirname(p), exist_ok=True); open(p, 'w', encoding='utf-8').write(t)
cv = lambda m: 'rsqmb_ldl_' + m.group(1).lower()
def deco(t):
    t = re.sub(r'(ACTOR\s+LDCustomFunction\s*:\s*)CustomInventory', r'\1RSQMB_LDLFn', t, flags=re.I)
    t = re.sub(r'(actor\s+LDMaxHax)\s*\n', r'\1 : RSQMB_LDLHax\n', t, flags=re.I)
    t = re.sub(r'CallACS\s*\(\s*"PlayerCount"\s*(,\s*0\s*)?\)', 'RSQLDL_Players()', t, flags=re.I)
    t = re.sub(r'CallACS\s*\(\s*"DRLALDLiteCheck"\s*(,[^)]*)?\)', 'RSQLDL_Compat(1)', t, flags=re.I)
    t = re.sub(r'CallACS\s*\(\s*"GuncasterLDLiteCheck"\s*(,[^)]*)?\)', 'RSQLDL_Compat(2)', t, flags=re.I)
    t = re.sub(r'CallACS\s*\(\s*"HideousDestructorLDLiteCheck"\s*(,[^)]*)?\)', 'RSQLDL_Compat(3)', t, flags=re.I)
    t = re.sub(r'CallACS\s*\(\s*"LD_(\w+)"\s*(,\s*0\s*)?\)', lambda m: 'GetCVar("rsqmb_ldl_%s")' % m.group(1).lower(), t, flags=re.I)
    t = re.sub(r'ACS_NamedExecuteAlways\s*\(\s*"LDMonsterInit"\s*,\s*0\s*\)', 'RSQLDL_Init()', t, flags=re.I)
    t = re.sub(r'ACS_NamedExecuteWithResult\s*\(\s*"Draw_Pentagram"\s*,', 'RSQLDL_Pentagram(', t, flags=re.I)
    t = re.sub(r'ACS_NamedExecute\w*\s*\(\s*"LDLite_HDCurser"\s*,\s*([^)]*)\)', r'RSQLDL_HDCurser(\1)', t, flags=re.I)
    t = re.sub(r'\s+Light\s*\(\s*"LDMonsterGlow\w+"\s*\)', '', t)        # the afterimages' lights: one on the monster now
    t = t.replace('"effects/legendaryenemyboss"', '"rsqmb/ldl/boss"')
    t = t.replace('#include "actors/', '#include "decorate/ldlite/')
    left = re.findall(r'(CallACS|ACS_\w+)\s*\(\s*"[^"]*"', t)
    assert not left, left
    return t
hdr = '// Yholl\'s LegenDoom Lite, in RSQ Miniboss (generated by tools/gen_ldlite.py from original/LegenDoomLite; edit there)\n'
files = {'decorate/ldlite/main.txt': deco(rd('DECORATE'))}
for f in os.listdir(os.path.join(S, 'actors')): files['decorate/ldlite/' + f] = deco(rd('actors/' + f))
for g in os.listdir(os.path.join(S, 'filter')): files['filter/%s/decorate.txt' % g] = deco(rd('filter/%s/decorate.txt' % g))
# PARENTS GET A PRIVATE NAME (rig 2026-11-23 gate4: with LegenDoom loaded, the engine keeps ITS class for every shared name,
# so a copy here inheriting "LDCustomFunction" got LegenDoom's, which has no RSQLDL_* functions: fatal). Every class of his
# that another of his inherits from is defined as RSLDL_<name>; his name stays as a thin alias of it (so whatever asks for
# it by name finds it), and his children inherit the private one, never LegenDoom's.
defre = re.compile(r'^(\s*actor\s+)(\w+)(\s*(?::\s*(\w+))?)', re.I | re.M)
classes, parents = set(), set()
for t in files.values():
    for m in defre.finditer(t):
        classes.add(m.group(2).lower())
        if m.group(4): parents.add(m.group(4).lower())
priv = {c for c in parents if c in classes}
def privatise(t):
    out, pos = [], 0
    for m in defre.finditer(t):
        name, par = m.group(2), m.group(4)
        head = m.group(1) + (('RSLDL_' + name) if name.lower() in priv else name)
        tail = m.group(3)
        if par and par.lower() in priv: tail = tail.replace(par, 'RSLDL_' + par)
        out.append(t[pos:m.start()]); out.append(head + tail); pos = m.end()
    out.append(t[pos:])
    t = ''.join(out)
    # the aliases, after the file
    al = [n for n in re.findall(r'^\s*actor\s+RSLDL_(\w+)', t, re.I | re.M)]
    if al: t += '\n// his names, kept (aliases of the private parents above)\n' + ''.join('ACTOR %s : RSLDL_%s {}\n' % (n, n) for n in al)
    return t
for k, t in files.items(): wr(k, hdr + privatise(t))
wr('DECORATE', '// RSQ Miniboss: Yholl\'s LegenDoom Lite (stands down while LegenDoom is loaded: zscript/rsqmb/ldlite.zs)\n#include "decorate/ldlite/main.txt"\n')
# cvars, menu, language
c = re.sub(r'\bLD_(\w+)', cv, rd('CVARINFO'))
c = '// ---- Yholl\'s LegenDoom Lite (his CVARINFO, LD_ -> rsqmb_ldl_) ----\nserver bool rsqmb_ldl = true;   // LegenDoom Lite built in (stands down while LegenDoom is loaded)\n' + c
m = rd('MENUDEF')
m = re.sub(r'OptionMenu\s+"OptionsMenu"\s*\{.*?\n\}\s*\n', '', m, count=1, flags=re.S)     # his copy of the whole Options menu: not kept
m = re.sub(r'\bLD_(\w+)', cv, m)
m = re.sub(r'"\$LD_MENU_', '"$RSQMB_LDL_MENU_', m)
for a, b in (('"LegenDoomLite"', '"RSQMB_LDLite"'), ('"LDLYhollMods"', '"RSQMB_LDLYholl"'), ('"LDLOtherMods"', '"RSQMB_LDLOther"'),
             ('"DoomRLA"', '"RSQMB_LDLDoomRLA"'), ('"FinalDoomer"', '"RSQMB_LDLFinalDoomer"')):
    m = m.replace(a, b)
for ov in re.findall(r'OptionValue\s+"(\w+)"', m): m = re.sub(r'"%s"' % ov, '"RSQMB_LDL_%s"' % ov, m)
m = '// ---- Yholl\'s LegenDoom Lite (his MENUDEF; ids RSQMB_LDL*, cvars rsqmb_ldl_*) ----\nAddOptionMenu "OptionsMenu"\n{\n\tSubMenu "LegenDoom Lite (RSQ Boss)", "RSQMB_LDLite"\n}\n' + m
l = re.sub(r'\bLD_MENU_', 'RSQMB_LDL_MENU_', rd('LANGUAGE.menu'))
l = re.sub(r'\bLD_(healthtier|bosshealthtier)', r'rsqmb_ldl_\1', l)
wr('LANGUAGE.ldlite', l)
# sounds and the skull
os.makedirs(os.path.join(M, 'sounds/ldlite'), exist_ok=True)
shutil.copy2(os.path.join(S, 'sounds/LDLELOOP'), os.path.join(M, 'sounds/ldlite/LDLELOOP'))
shutil.copy2(os.path.join(S, 'sounds/LDLETRAN'), os.path.join(M, 'sounds/ldlite/LDLETRAN'))
shutil.copy2(os.path.join(S, 'sounds/LDLEBOSS'), os.path.join(M, 'sounds/ldlite/RSLDLBOS'))
s = rd('SNDINFO').replace('LDLEBOSS', 'RSLDLBOS').replace('effects/legendaryenemyboss', 'rsqmb/ldl/boss')
os.makedirs(os.path.join(M, 'sprites/ldlite'), exist_ok=True)
for f in ('SCULA0', 'SCULB0'): shutil.copy2(os.path.join(S, 'sprites', f), os.path.join(M, 'sprites/ldlite', f))
# his lights, unchanged (no name of his GLDEFS is LegenDoom's): ldlite.zs attaches one to the monster by name
wr('GLDEFS.ldlite', rd('GLDEFS'))
wr('SNDINFO.ldlite', s)
wr('CVARINFO.ldlite', c)
wr('MENUDEF.ldlite', m)
c2 = rd('CREDITS')
wr('CREDITS.ldlite', c2)
print('ldlite: files written')
