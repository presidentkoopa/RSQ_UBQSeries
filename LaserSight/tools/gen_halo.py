#!/usr/bin/env python3
"""gen_halo.py -- the halo rods of Beam Type: Glow (owner 2026-11-06): the soft glow around the beam's core.

    python3 tools/gen_halo.py <LaserSight folder> [placements: all (default) or 0,1,2,...]

Reads placements from zscript/rsqls/muzzles.zs (PLACE: Offset, muzzle, barrel, layer y) and LENGTHS,
writes models/rsqls/halo/hNNkMM.kvx and VOXELDEF.halo for the placements given (every placement x every
length), plus zscript/rsqls/halo_gen.zs listing the halo sprites. Rerun it whenever muzzles.zs changes.

Halo rod: a HOLLOW PLUS cross-section (four 1-voxel-thick arms around an empty axis, where the
core rod lies), HALO_S cm per voxel, arm length tapering with distance. Palette index encodes
(ring r = 1..RINGS, distance bin): idx = 1 + (r-1)*DB + bin. The runtime translation turns each
index into colour x fade(distance) x falloff(ring).
"""
import math, os, re, struct, sys

ROOT = sys.argv[1]
HALO_S = float(os.environ.get('HALO_S', '0.4'))
HW0 = int(os.environ.get('HW0', '3'))       # arm length (voxels) at the muzzle
HW1 = int(os.environ.get('HW1', '1'))       # arm length at TAPER_CM and beyond
TAPER_CM = float(os.environ.get('TAPER_CM', '400'))
RINGS = 4
ARMS = int(os.environ.get('ARMS', '8'))
DB = 63
FADE_MAX = 600.0
BEAM_S = 0.4

src = open(os.path.join(ROOT, 'zscript/rsqls/muzzles.zs')).read()
LENGTHS = [float(x) for x in re.search(r'LENGTHS\[\] = \{([^}]*)\}', src).group(1).split(',')]
pl = re.search(r'PLACE\[\] = \{([^}]*)\}', src).group(1)
PLACE = [float(x) for x in re.findall(r'-?\d+\.\d+', pl)]
K = len(LENGTHS)
ARG = sys.argv[2] if len(sys.argv) > 2 else 'all'
PLACES = list(range(len(PLACE) // 10)) if ARG == 'all' else [int(x) for x in ARG.split(',')]

def Ry(a, v):
    a = math.radians(a); c, s = math.cos(a), math.sin(a)
    return (c * v[0] + s * v[2], v[1], -s * v[0] + c * v[2])
def Rx(a, v):
    a = math.radians(a); c, s = math.cos(a), math.sin(a)
    return (v[0], c * v[1] - s * v[2], s * v[1] + c * v[2])

def rod_angles(d):
    theta = math.degrees(math.atan2(math.hypot(d[1], d[2]), d[0]))
    phi = math.degrees(math.atan2(d[1], -d[2]))
    return theta, phi

def b36(i):
    s = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'
    return s[i // 36] + s[i % 36]

def arm(x):
    d = (x + 0.5) * HALO_S
    u = min(1.0, d / TAPER_CM)
    return max(HW1, int(round(HW0 + (HW1 - HW0) * u)))

def write_kvx(path, n, pivot):
    W = 2 * HW0 + 1
    c = HW0
    occ = {}
    for x in range(n):
        d = (x + 0.5) * HALO_S
        b = 1 + min(DB - 1, int(d / FADE_MAX * DB))
        a = arm(x)
        for r in range(1, a + 1):
            idx = 1 + (r - 1) * DB + (b - 1)
            for (y, z) in ((c + r, c), (c - r, c), (c, c + r), (c, c - r)):
                occ[(x, y, z)] = idx
        if ARMS == 8:
            for r in range(1, a + 1):
                rr = int(round(r * 1.4142))
                if rr > a: break
                idx = 1 + (rr - 1) * DB + (b - 1)
                for (y, z) in ((c + r, c + r), (c - r, c + r), (c + r, c - r), (c - r, c - r)):
                    occ[(x, y, z)] = idx
    xs, ys, zs = n, W, W
    def has(x, y, z): return (x, y, z) in occ
    xoff, xyall, data = [], [], b''
    offsetsize = (xs + 1) * 4 + xs * (ys + 1) * 2
    pos = offsetsize
    for x in range(xs):
        xoff.append(pos)
        colstart = len(data)
        xy = []
        for y in range(ys):
            xy.append(len(data) - colstart)
            for z in range(zs):
                if not has(x, y, z): continue
                cull = ((0 if has(x - 1, y, z) else 1) | (0 if has(x + 1, y, z) else 2) |
                        (0 if has(x, y - 1, z) else 4) | (0 if has(x, y + 1, z) else 8) |
                        (0 if has(x, y, z - 1) else 16) | (0 if has(x, y, z + 1) else 32))
                data += bytes([z, 1, cull, occ[(x, y, z)]])
        xy.append(len(data) - colstart)
        xyall += xy
        pos = offsetsize + len(data)
    xoff.append(pos)
    body = struct.pack('<6i', xs, ys, zs, *[int(round(p * 256)) for p in pivot])
    body += struct.pack('<%di' % len(xoff), *xoff) + struct.pack('<%dh' % len(xyall), *xyall) + data
    pal = bytes(sum(([i >> 2] * 3 for i in range(256)), []))
    with open(path, 'wb') as f:
        f.write(struct.pack('<i', len(body)) + body + pal)

hdir = os.path.join(ROOT, 'models/rsqls/halo'); os.makedirs(hdir, exist_ok=True)
vd = ['// GENERATED by tools/gen_halo.py -- the halo rods of Beam Type: Glow (every placement x every length)']
sprites = []
frames = {}
for pi in PLACES:
    b = pi * 10
    off = tuple(PLACE[b:b + 3]); q0 = tuple(PLACE[b + 3:b + 6]); d = tuple(PLACE[b + 6:b + 9])
    theta, phi = rod_angles(d)
    t = Ry(-theta, Rx(-phi, q0)); t = tuple(v / HALO_S for v in t)
    W = 2 * HW0 + 1
    pivot = (-t[0], t[2] + W / 2.0, t[1] + W / 2.0)
    for k, L in enumerate(LENGTHS):
        g = pi * K + k
        spr = 'LH' + b36(g // 26)
        if spr not in sprites: sprites.append(spr)
        fr = chr(65 + g % 26)
        frames.setdefault(spr, '')
        frames[spr] += fr
        n = max(1, int(round(L / HALO_S)))
        fn = 'h%02dk%02d.kvx' % (pi, k)
        write_kvx(os.path.join(hdir, fn), n, pivot)
        vd.append('%s%s = "models/rsqls/halo/%s" { Scale = %.4f AngleOffset = %.4f XOffset = %.4f YOffset = %.4f ZOffset = %.4f OverridePalette }'
                  % (spr, fr, fn, HALO_S, -theta, off[0], off[2], off[1]))
open(os.path.join(ROOT, 'VOXELDEF.halo'), 'w').write('\n'.join(vd) + '\n')
# every possible halo sprite name, for the runtime's index table; and states naming the made ones
allspr = ['LH' + b36(i) for i in range((PLACE.__len__() // 10 * K + 25) // 26)]
z = ['// GENERATED by tools/gen_halo.py -- the halo sprites of Beam Type: Glow', 'class RSQLS_HaloSprites abstract', '{',
     '\tstatic const String SPRITES[] = { %s };' % ', '.join('"%s"' % s for s in allspr),
     '\tconst RINGS = %d;' % RINGS, '\tconst DB = %d;' % DB, '}',
     'class RSQLS_HaloStates : Actor', '{', '\tStates', '\t{', '\tHalos:']
for s in sprites: z.append('\t\t%s %s -1;' % (s, frames[s]))
z += ['\t\tStop;', '\t}', '}', '']
open(os.path.join(ROOT, 'zscript/rsqls/halo_gen.zs'), 'w').write('\n'.join(z))
print('halo: %d placements x %d lengths, sprites %s..%s' % (len(PLACES), K, sprites[0], sprites[-1]))
