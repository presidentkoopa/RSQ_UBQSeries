#!/usr/bin/env python3
"""gen_bdbore.py -- Brutal Doom VR 2.0's own shot line, PARSED from its code, for the laser's dot.

    python3 tools/gen_bdbore.py <BD22_VR-Reloaded pk3>

BD22 VR Reloaded 2.0 (fix-accuracy) re-fires every shot of a gun with a bore from that gun's muzzle (RSQ_Muzzle.Muzzle,
F L U cm in the controller's frame) down its bore (RSQ_Muzzle.Bore, one unit vector for every ported gun), so the shot
leaves 3.85 deg left and 3.36 deg up of the controller's forward, along the drawn barrel. The laser's dot has to follow
that line, not a line measured off a mesh. This reads both straight out of zscript/rsq/muzzle.zs -- the checks in
order, `n == 'X'` (exact class) or `w is 'X'` -- and writes zscript/rsqls/bdbore.zs. Nothing is typed in by hand."""
import os, re, sys, zipfile, math

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)

TAIL = r"""	// Brutal Doom's own: is its muzzle handler running (BD22 VR Reloaded 2.0 and later)?
	static bool Active()
	{
		return EventHandler.Find("RSQ_Muzzle") != null;
	}

	// A direction in the hand's own frame (yaw 0 pitch 0 forward, yaw 90 left, pitch 90 up), as Brutal Doom's
	// RSVR_VRHand.HandDir / OffDir build it: (angle, Doom pitch) from the engine, and its map vector with the hand
	// transform's 1/pixelstretch taken back out (for placing the muzzle).
	static Vector2 Angles(PlayerPawn mo, int h, double yaw, double pitch)
	{
		if (!mo.OverrideAttackPosDir) return (mo.angle + yaw, mo.pitch + pitch);
		Vector3 ap = (h == 0) ? mo.AttackDir(mo, mo.angle + yaw, mo.pitch + pitch) : mo.OffhandDir(mo, mo.angle + yaw, mo.pitch + pitch);
		return ap.xy;
	}
	static Vector3 Axis(PlayerPawn mo, int h, double yaw, double pitch, double ps)
	{
		Vector2 ap = Angles(mo, h, yaw, pitch);
		double cp = cos(ap.y);
		Vector3 v = (cp * cos(ap.x), cp * sin(ap.x), -sin(ap.y) * ps);
		double l = v.Length();
		return l > 0 ? v / l : (1, 0, 0);
	}

	// THE SHOT LINE Brutal Doom fires a bored gun down (muzzle.zs Where / WorldHitscanPreFired): from the muzzle (the
	// controller itself when a wall is between them), at the attack's angles plus the bore's. Returns the start and the
	// unit direction (Doom map space, the angles the engine's own LineAttack takes).
	static bool, Vector3, Vector3 Line(PlayerPawn mo, int h, Weapon w)
	{
		bool got; double f, l, u;
		[got, f, l, u] = Muzzle(w);
		if (!got || !mo || !mo.OverrideAttackPosDir) return false, (0, 0, 0), (0, 0, 0);
		double ps = mo.Level.pixelstretch;
		if (ps <= 0) ps = 1.2;
		let cv = CVar.FindCVar("vr_vunits_per_meter");
		double vu = cv ? cv.GetFloat() : 34;
		if (vu <= 0) vu = 34;
		Vector3 hp = (h == 0) ? mo.AttackPos : mo.OffhandPos;
		Vector3 w3 = (Axis(mo, h, 0, 0, ps) * f + Axis(mo, h, 90, 0, ps) * l + Axis(mo, h, 0, 90, ps) * u) * (vu / 100.0);
		w3.z /= ps;
		Vector3 at = hp + w3;
		double len = w3.Length();
		if (len > 0)
		{
			FLineTraceData tr;
			mo.LineTrace(VectorAngle(w3.x, w3.y), len, -asin(clamp(w3.z / len, -1, 1)), TRF_ABSPOSITION | TRF_THRUACTORS, hp.z, hp.x, hp.y, tr);
			if (tr.HitType != TRACE_HitNone) at = hp;
		}
		Vector2 sa = Angles(mo, h, BORE_YAW, BORE_PITCH);
		double cp = cos(sa.y);
		return true, at, (cp * cos(sa.x), cp * sin(sa.x), -sin(sa.y));
	}"""

def main():
    src = zipfile.ZipFile(sys.argv[1]).read('zscript/rsq/muzzle.zs').decode('latin-1')
    m = re.search(r'static Vector3 Muzzle\(Weapon w\)(.*?)\n\t}', src, re.S)
    body = m.group(1)
    rows = re.findall(r"if \((n == '(\w+)'|w is '(\w+)')\)\s*return \(([-\d.]+), ([-\d.]+), ([-\d.]+)\);", body)
    b = re.search(r'static Vector3 Bore\(Weapon w\).*?return \(([-\d.]+), ([-\d.]+), ([-\d.]+)\);\s*\n\t}', src, re.S)
    bore = tuple(float(x) for x in b.groups())
    excl = re.findall(r"HasBore\(Weapon w\)\s*\{\s*return w && (.*?)Muzzle", src, re.S)[0]
    no_bore = re.findall(r"!\(w is '(\w+)'\)", excl)
    yaw = math.degrees(math.atan2(bore[1], bore[0])); pitch = math.degrees(math.asin(bore[2]))
    out = ['// GENERATED by tools/gen_bdbore.py from %s zscript/rsq/muzzle.zs -- do not edit.' % os.path.basename(sys.argv[1]),
           '// Brutal Doom VR 2.0\'s shot line: muzzle F L U cm in the controller frame, the bore as yaw left / pitch up.',
           'class RSQLS_BDBore play', '{',
           '\tconst BORE_YAW = %.4f;' % yaw, '\tconst BORE_PITCH = %.4f;' % pitch, '',
           '\t// (found, F, L, U): the checks in Brutal Doom\'s own order',
           '\tstatic bool, double, double, double Muzzle(Weapon w)', '\t{', '\t\tif (!w) return false, 0, 0, 0;',
           '\t\tName n = w.GetClassName();']
    for c in no_bore:
        out.append("\t\tif (KindOf(w, '%s')) return false, 0, 0, 0;   // no bore: aimed its own way" % c)
    for full, exact, iscls, f, l, u in rows:
        if exact:
            out.append("\t\tif (n == '%s') return true, %s, %s, %s;" % (exact, f, l, u))
        else:
            out.append("\t\tif (KindOf(w, '%s')) return true, %s, %s, %s;" % (iscls, f, l, u))
    out += ['\t\treturn false, 0, 0, 0;', '\t}', '',
            '\t// `w is X` by name: X may not exist without Brutal Doom loaded', '\tstatic bool KindOf(Weapon w, String c)', '\t{',
            '\t\tclass<Actor> k = c;', '\t\treturn k && (w is k);', '\t}', '', TAIL, '}', '']
    open(os.path.join(ROOT, 'zscript', 'rsqls', 'bdbore.zs'), 'w').write('\n'.join(out))
    print('%d guns, bore yaw %.3f pitch %.3f, no bore: %s' % (len(rows), yaw, pitch, no_bore))

main()
