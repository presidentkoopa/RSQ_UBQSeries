#!/usr/bin/env python3
"""build_monster_art.py -- the colour ladder's painted monster art, one pk3 per colour.

    python tools/build_monster_art.py                      every colour that has art in MonsterRecolour/rsrecolour/
    python tools/build_monster_art.py green red            just those colours
    python -I tools/build_monster_art.py --brightmaps A.wad B.pk3 ...
                                                           (re)write MonsterRecolour/brightmaps.txt from a load order

Writes pk3/RSQ_MonsterArt_<Colour>.pk3: rsrecolour/<colour>/<LUMP>.png (whatever families are painted at the time),
rsrecolour/<colour>/sprites.txt (the sprite names that have art: the driver's quick test) and a GLDEFS.txt giving each painted frame its source sprite's brightmap (MonsterRecolour/brightmaps.txt, read once from
Brutal Doom 22 + XMVE's own GLDEFS by --brightmaps, so this build needs nothing outside the repo). RSQ Monsters'
RS_BDArt.zs finds the frames by full path; load the art pk3s after RSQ_Monsters.pk3.

Why one pk3 per colour: all of Brutal Doom 22 + XMVE is about 11,300 lumps x 12 colours (about 135,000 PNGs, 300 MB);
a plain zip holds 65,535 entries, and GitHub takes no file over 100 MB. The build stops if a colour's pk3 would break
either. PNGs are stored, not deflated (they are compressed already)."""
import os, sys, zipfile

HUB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(HUB, 'MonsterRecolour', 'rsrecolour')
BMT = os.path.join(HUB, 'MonsterRecolour', 'brightmaps.txt')
OUT = os.path.join(HUB, 'pk3')
COLOURS = ['green', 'blue', 'purple', 'cyan', 'brown', 'yellow', 'fireblu', 'gray', 'red', 'abyss', 'black', 'white']
TITLE = {'fireblu': 'FireBlu'}
MAX_ENTRIES = 65535
MAX_BYTES = 100 * 1000 * 1000


def pk3_name(col):
    return 'RSQ_MonsterArt_%s.pk3' % TITLE.get(col, col.capitalize())


def write_brightmaps(archives):
    sys.path.insert(0, os.path.join(HUB, 'Monsters', 'tools', 'recolour'))
    import lumps
    lo = lumps.LoadOrder(archives)
    with open(BMT, 'w', newline='\n') as f:
        f.write('# GENERATED by tools/build_monster_art.py --brightmaps: sprite lump <TAB> its GLDEFS brightmap body, read from\n')
        f.write('# the load order below (the last archive that defines one wins). The art build gives each painted copy the same.\n')
        for a in archives:
            f.write('# %s\n' % os.path.basename(a))
        for k in sorted(lo.brightmaps):
            f.write('%s\t%s\n' % (k, lo.brightmaps[k]))
    print('wrote %s (%d brightmaps)' % (os.path.relpath(BMT, HUB), len(lo.brightmaps)))


def read_brightmaps():
    bm = {}
    if not os.path.isfile(BMT):
        print('warning: %s missing: the art pk3s get no brightmaps (run with --brightmaps)' % os.path.relpath(BMT, HUB))
        return bm
    for line in open(BMT):
        if line.startswith('#') or '\t' not in line: continue
        k, v = line.rstrip('\n').split('\t', 1)
        bm[k.upper()] = v
    return bm


def build(col, bm):
    d = os.path.join(ART, col)
    pngs = sorted(f for f in os.listdir(d) if f.lower().endswith('.png')) if os.path.isdir(d) else []
    out = os.path.join(OUT, pk3_name(col))
    if not pngs:
        if os.path.exists(out): os.remove(out)
        print('%s: no art, no pk3' % col)
        return
    if len(pngs) + 3 > MAX_ENTRIES:
        sys.exit('%s: %d frames: over the zip limit of %d entries' % (col, len(pngs), MAX_ENTRIES))
    gl = ['// GENERATED by tools/build_monster_art.py: the painted %s frames keep their source sprites\' brightmaps' % col]
    nb = 0
    for f in pngs:
        lump = f[:-4].upper()
        if lump in bm:
            gl.append('brightmap texture "rsrecolour/%s/%s" { %s }' % (col, f, bm[lump])); nb += 1
    # the sprite names that have art in this colour: RS_BDArt.zs reads it once, so a frame of a sprite with no art here
    # costs one Map lookup a tic, not a texture lookup
    sprites = sorted(set(f[:4].upper() for f in pngs))
    tmp = out + '.tmp'
    with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_STORED) as z:
        z.writestr(zipfile.ZipInfo('GLDEFS.txt', (2026, 11, 13, 0, 0, 0)), '\n'.join(gl) + '\n', zipfile.ZIP_DEFLATED)
        z.writestr(zipfile.ZipInfo('rsrecolour/%s/sprites.txt' % col, (2026, 11, 13, 0, 0, 0)), ' '.join(sprites) + '\n', zipfile.ZIP_DEFLATED)
        for f in pngs:
            zi = zipfile.ZipInfo('rsrecolour/%s/%s' % (col, f), (2026, 11, 13, 0, 0, 0))
            with open(os.path.join(d, f), 'rb') as fh:
                z.writestr(zi, fh.read(), zipfile.ZIP_STORED)
    size = os.path.getsize(tmp)
    if size >= MAX_BYTES:
        os.remove(tmp)
        sys.exit('%s: %.1f MB: over GitHub\'s 100 MB file limit (split the colour by family)' % (col, size / 1e6))
    os.replace(tmp, out)
    print('built pk3/%s (%d frames of %d sprites, %d brightmaps, %.1f MB)' % (pk3_name(col), len(pngs), len(sprites), nb, size / 1e6))


if __name__ == '__main__':
    args = sys.argv[1:]
    if args[:1] == ['--brightmaps']:
        write_brightmaps(args[1:])
        sys.exit(0)
    want = [a.lower() for a in args] or COLOURS
    for c in want:
        if c not in COLOURS: sys.exit('unknown colour: %s (one of: %s)' % (c, ', '.join(COLOURS)))
    os.makedirs(OUT, exist_ok=True)
    bm = read_brightmaps()
    for c in want:
        build(c, bm)
