#!/usr/bin/env python3
"""gen_kinds.py -- TEST/BUILD TOOL (never ships). The grenade KINDS' skins (GBOVR_TREES.md 4.5 Kinds; the owner's pick, 11-02:
the WIDE BAND way of Grenade/docs/grenade_kinds_mockup2.png): Gomuz's own nade.png with the red stripe across the top
widened to rows 24-64 and every red part (the stripe, the spoon patch) recoloured to the kind's colour, each pixel's
brightness kept; the body as shipped. Nothing drawn new. Also writes, from the same table:
  models/rsqgn/nade_<kind>.png                      the eight skins (the frag keeps nade.png)
  MODELDEF.kinds.txt                                the kinds' model blocks (held: ring in, pin out, cooking; thrown)
  sprites/rsqgn/QGKnA0..C0.png, QGTnA0              the sprite lumps those blocks name (copies of the frag's)
    python3 Grenade/tools/gen_kinds.py"""
import os, shutil
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
M = os.path.join(ROOT, 'models', 'rsqgn')
SP = os.path.join(ROOT, 'sprites', 'rsqgn')
# kind number (RSQGN_Handler K_*), name, colour (the owner's, GBOVR_TREES.md)
KINDS = [
    (1, 'impact', (255, 120, 20)),
    (2, 'incendiary', (255, 200, 40)),
    (3, 'freeze', (70, 190, 255)),
    (4, 'stun', (170, 80, 255)),
    (5, 'smoke', (140, 140, 150)),
    (6, 'flash', (255, 255, 255)),
    (7, 'charm', (255, 110, 190)),
    (8, 'infight', (60, 220, 90)),
]
BAND = (24, 64)


def is_red(p):
    r, g, b = p
    return r > 70 and r > g * 1.6 and r > b * 1.6


def skin(colour):
    im = Image.open(os.path.join(M, 'nade.png')).convert('RGB')
    px = im.load()
    w, h = im.size
    cr, cg, cb = colour
    for y in range(h):
        band = BAND[0] <= y <= BAND[1]
        for x in range(w):
            p = px[x, y]
            if is_red(p):
                v = min(1.0, p[0] / 255.0 * 1.35)
            elif band:
                l = 0.299 * p[0] + 0.587 * p[1] + 0.114 * p[2]
                v = min(1.0, 0.25 + l / 255.0 * 1.2)
            else:
                continue
            px[x, y] = (int(cr * v), int(cg * v), int(cb * v))
    return im


HELD = """Model RSQGN_Grenade
{{
	Path "models/rsqgn"
	Model 0 "nade.md3"
	SurfaceSkin 0 0 "{s}"
	SurfaceSkin 0 1 "{s}"
	SurfaceSkin 0 2 "{s2}"
	SurfaceSkin 0 3 "{s3}"
	SurfaceSkin 0 4 "{s3}"
	Scale -0.92 0.92 0.92
	Offset -12.075 -8.898 0.0
	NoInterpolation
	ZOffset 2.326
	AngleOffset -18.317
	PitchOffset -17.735
	RollOffset 3.457
	FrameIndex {spr} {f} 0 2
}}
"""
THROWN = """Model RSQGN_Thrown
{{
	Path "models/rsqgn"
	Model 0 "nade.md3"
	SurfaceSkin 0 0 "{s}"
	SurfaceSkin 0 1 "{s}"
	SurfaceSkin 0 2 "rsqgn_clear.png"
	SurfaceSkin 0 3 "rsqgn_clear.png"
	SurfaceSkin 0 4 "rsqgn_clear.png"
	Scale 1.0 1.0 1.0
	Offset -28.53 0.02 5.947
	NoInterpolation
	USEACTORPITCH
	USEACTORROLL
	UseRotationCenter
	Rotation-Center 0 0 1.4
	FrameIndex {spr} A 0 2
}}
"""

out = ["// RSQ Grenade -- THE GRENADE KINDS (Gun Bonsai VR patch). GENERATED by tools/gen_kinds.py: edit the script, not this.",
       "// Each kind: QGKn A ring in, B pin out, C cooking (held, as MODELDEF.txt's QGNH A-C) and QGTn A (thrown, as QGNT A),",
       "// in that kind's skin. The fuse flashes keep the frag's red and amber (QGNH D / E, QGNT B / C).", ""]
for n, name, col in KINDS:
    fn = 'nade_%s.png' % name
    skin(col).save(os.path.join(M, fn))
    print('wrote', fn)
    clear = 'rsqgn_clear.png'
    out.append('// %s %s' % (name.upper(), col))
    out.append(HELD.format(s=fn, s2=fn, s3=fn, spr='QGK%d' % n, f='A'))
    out.append(HELD.format(s=fn, s2=clear, s3=fn, spr='QGK%d' % n, f='B'))
    out.append(HELD.format(s=fn, s2=clear, s3=clear, spr='QGK%d' % n, f='C'))
    out.append(THROWN.format(s=fn, spr='QGT%d' % n))
    for f in 'ABC':
        shutil.copyfile(os.path.join(SP, 'QGNH%s0.png' % f), os.path.join(SP, 'QGK%d%s0.png' % (n, f)))
    shutil.copyfile(os.path.join(SP, 'QGNTA0'), os.path.join(SP, 'QGT%dA0' % n))
with open(os.path.join(ROOT, 'MODELDEF.kinds.txt'), 'w', newline='\n') as f:
    f.write('\n'.join(out))
print('wrote MODELDEF.kinds.txt and the sprite lumps')
